import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from typing import Dict, List
import os
from datetime import datetime
from dotenv import load_dotenv
from services.weather_service import WeatherService

load_dotenv()

class AlertService:
    def __init__(self):
        self.weather_service = WeatherService()
        self.smtp_server = os.getenv("SMTP_SERVER", "smtp.gmail.com")
        self.smtp_port = int(os.getenv("SMTP_PORT", "587"))
        self.email_user = os.getenv("EMAIL_USER")
        self.email_password = os.getenv("EMAIL_PASSWORD")
        
    async def check_alerts_for_location(self, location, alert_preference, db):
        """Check if alerts should be triggered for a location"""
        try:
            # Get current weather for the location
            weather_data = await self.weather_service.get_current_weather(
                location.latitude, location.longitude
            )
            
            triggered_alerts = []
            
            # Check each alert type
            for alert_type in alert_preference.alert_types:
                threshold = alert_preference.threshold_values.get(alert_type, 0)
                
                if self._should_trigger_alert(alert_type, weather_data, threshold):
                    alert_message = self._generate_alert_message(
                        alert_type, weather_data, location.name
                    )
                    
                    triggered_alerts.append({
                        "alert_type": alert_type,
                        "message": alert_message,
                        "severity": self._determine_severity(alert_type, weather_data),
                        "weather_data": weather_data
                    })
            
            return triggered_alerts
            
        except Exception as e:
            print(f"Error checking alerts for location {location.name}: {e}")
            return []
    
    async def send_alert_email(self, user_email: str, location_name: str, alert_data: Dict):
        """Send alert email to user"""
        try:
            if not self.email_user or not self.email_password:
                print("Email credentials not configured")
                return False
            
            # Create email message
            msg = MIMEMultipart()
            msg['From'] = self.email_user
            msg['To'] = user_email
            msg['Subject'] = f"🌊 Marine Weather Alert - {location_name}"
            
            # Create email body
            body = f"""
            <html>
            <body>
                <h2>🌊 Marine Weather Alert</h2>
                <p><strong>Location:</strong> {location_name}</p>
                <p><strong>Alert Type:</strong> {alert_data['alert_type'].replace('_', ' ').title()}</p>
                <p><strong>Severity:</strong> {alert_data['severity'].upper()}</p>
                <p><strong>Time:</strong> {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}</p>
                
                <h3>Alert Details:</h3>
                <p>{alert_data['message']}</p>
                
                <h3>Current Conditions:</h3>
                <ul>
                    <li>Wind Speed: {alert_data['weather_data'].get('wind_speed', 'N/A')} km/h</li>
                    <li>Wave Height: {alert_data['weather_data'].get('wave_height', 'N/A')} m</li>
                    <li>Visibility: {alert_data['weather_data'].get('visibility', 'N/A')} m</li>
                    <li>Temperature: {alert_data['weather_data'].get('temperature', 'N/A')}°C</li>
                </ul>
                
                <p><em>This alert was generated by the Marine Weather & AI Hazard Assistant.</em></p>
            </body>
            </html>
            """
            
            msg.attach(MIMEText(body, 'html'))
            
            # Send email
            server = smtplib.SMTP(self.smtp_server, self.smtp_port)
            server.starttls()
            server.login(self.email_user, self.email_password)
            text = msg.as_string()
            server.sendmail(self.email_user, user_email, text)
            server.quit()
            
            return True
            
        except Exception as e:
            print(f"Error sending alert email: {e}")
            return False
    
